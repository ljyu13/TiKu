ALL = {
    "primary": PRIMARY,
    "junior_high": JUNIOR,
    "senior_high": SENIOR,
}


def main():
    manifest = {}
    for stage, subjects in ALL.items():
        folder = BASE / DIRS[stage]
        folder.mkdir(parents=True, exist_ok=True)
        manifest[stage] = {}
        for subject, (title, questions) in subjects.items():
            pid = "ljyu-original-%s-%s" % (DIRS[stage], subject)
            prefix = "ljyu-%s-%s" % (CODE[stage], SUBCODE[subject])
            qlist = []
            for i, item in enumerate(questions, 1):
                row = {"id": "%s-%02d" % (prefix, i)}
                row.update(item)
                qlist.append(row)
            bank = {
                "format": "wrong-notebook-question-bank",
                "version": 1,
                "meta": {
                    "id": pid,
                    "title": title,
                    "stage": stage,
                    "subject": subject,
                    "grades": [],
                    "count": len(qlist),
                    "tagged": True,
                    "source": "ljyu13 原创编写",
                    "license": "CC-BY-NC-4.0",
                    "updatedAt": TODAY,
                },
                "questions": qlist,
            }
            path = folder / (pid + ".json")
            text = json.dumps(bank, ensure_ascii=False, indent=2) + "\n"
            path.write_text(text, encoding="utf-8")
            manifest[stage][subject] = len(qlist)
            print("生成 %s：%d 题" % (path.relative_to(ROOT), len(qlist)))
    total = sum(sum(v.values()) for v in manifest.values())
    print("完成：%d 个学科包，%d 道题" % (sum(len(v) for v in manifest.values()), total))


if __name__ == "__main__":
    main()
