def c_poem_prev(b):
    up, down, author, dyn, title = b.rng.choice(POEMS)
    others = b.rng.sample([p[0] for p in POEMS if p[0] != up], 3)
    b.choice("诗句\"%s\"的上一句是？" % down, up, others,
             "出自%s代%s《%s》：%s，%s。" % (dyn, author, title, up, down),
             ["古诗默写", title])


def c_poem_author(b):
    up, down, author, dyn, title = b.rng.choice(POEMS)
    authors = list(set(p[2] for p in POEMS))
    others = b.rng.sample([a for a in authors if a != author], 3)
    b.choice("诗句\"%s，%s\"的作者是谁？" % (up, down), author, others,
             "这句诗出自%s代诗人%s的《%s》。" % (dyn, author, title),
             ["文学常识", "作者"])


def c_poem_fill(b):
    up, down, author, dyn, title = b.rng.choice(POEMS)
    b.fill("补写诗句：%s，___。" % up, down,
           "出自%s代%s《%s》，下句是\"%s\"。" % (dyn, author, title, down),
           ["古诗默写", title])


def c_poem_judge(b):
    up, down, author, dyn, title = b.rng.choice(POEMS)
    if b.rng.random() < 0.5:
        b.judge("\"%s，%s\"出自%s的《%s》。" % (up, down, author, title), True,
                "这句诗确实出自%s代%s的《%s》。" % (dyn, author, title),
                ["文学常识", title])
    else:
        wrong = b.rng.choice([p for p in POEMS if p[2] != author])[2]
        b.judge("\"%s，%s\"的作者是%s。" % (up, down, wrong), False,
                "这句诗的作者是%s，不是%s。" % (author, wrong), ["文学常识"])


def c_idiom_mean(b):
    idiom, mean = b.rng.choice(IDIOMS)
    others = b.rng.sample([x[1] for x in IDIOMS if x[1] != mean], 3)
    b.choice("成语\"%s\"的意思是？" % idiom, mean, others,
             "%s：%s。" % (idiom, mean), ["成语理解"])


def c_idiom_fill(b):
    idiom, mean = b.rng.choice(IDIOMS)
    b.fill("根据意思写成语：%s → ___" % mean, idiom,
           "这个意思对应的成语是\"%s\"。" % idiom, ["成语理解"])


def c_idiom_judge(b):
    idiom, mean = b.rng.choice(IDIOMS)
    if b.rng.random() < 0.5:
        b.judge("成语\"%s\"的意思是%s。" % (idiom, mean), True,
                "%s 的意思确实是%s。" % (idiom, mean), ["成语理解"])
    else:
        wrong = b.rng.choice([x[1] for x in IDIOMS if x[1] != mean])
        b.judge("成语\"%s\"的意思是%s。" % (idiom, wrong), False,
                "%s 的意思是%s，不是%s。" % (idiom, mean, wrong), ["成语理解"])


def c_lit(b):
    name, cat, desc = b.rng.choice(LIT)
    same = [x[0] for x in LIT if x[1] == cat and x[0] != name]
    b.choice("关于\"%s\"，下列说法正确的是？" % name, desc,
             b.rng.sample([x[2] for x in LIT if x[0] in same] or
                          [x[2] for x in LIT if x[2] != desc], 3),
             "%s：%s。" % (name, desc), ["文学常识", cat])


def c_lit_judge(b):
    name, cat, desc = b.rng.choice(LIT)
    if b.rng.random() < 0.5:
        b.judge("%s：%s。" % (name, desc), True,
                "表述正确：%s 是%s。" % (name, desc), ["文学常识"])
    else:
        other = b.rng.choice([x for x in LIT if x[0] != name])
        b.judge("%s：%s。" % (name, other[2]), False,
                "%s 的正确表述是\"%s\"。" % (name, desc), ["文学常识"])


def c_rhetoric(b):
    sent, fig = b.rng.choice(RHETORIC)
    figs = ["比喻", "拟人", "夸张", "排比", "反问", "设问"]
    others = [f for f in figs if f not in fig][:3]
    b.choice("句子\"%s\"主要运用了什么修辞手法？" % sent, fig, others,
             "这句话运用了%s的修辞手法。" % fig, ["修辞手法"])


def c_assoc(b):
    pair, rel = b.rng.choice(ASSOCIATIONS)
    rels = ["转折关系", "因果关系", "递进关系", "假设关系", "条件关系", "并列关系"]
    b.choice("关联词\"%s\"表示什么关系？" % pair, rel,
             [r for r in rels if r != rel][:3],
             "\"%s\"表示%s。" % (pair, rel), ["关联词"])


def c_pronunciation(b):
    if not PRONUNCIATION:
        return
    word, right, wrong = b.rng.choice(PRONUNCIATION)
    b.choice("词语\"%s\"中加点字的正确读音是？" % word, right,
             [wrong, right[0] + "a", "ā"],
             "\"%s\"的正确读音是 %s。" % (word, right), ["字音"])


def c_bug_sentence(b):
    cases = [
        ("通过这次活动，使我明白了许多道理。", "缺少主语", "删去\"通过\"或\"使\""),
        ("他大约十岁左右。", "语义重复", "删去\"大约\"或\"左右\""),
        ("我们要不断改进学习成绩。", "搭配不当", "把\"改进\"改为\"提高\""),
        ("能否努力学习，是取得成功的关键。", "两面对一面", "删去\"能否\""),
        ("防止不再发生类似事故。", "否定不当", "删去\"不\""),
        ("这本书对我很感兴趣。", "主客颠倒", "改为\"我对这本书很感兴趣\""),
        ("他的写作水平明显改进了。", "搭配不当", "把\"改进\"改为\"提高\""),
        ("全班同学都到了，只有小明没来。", "前后矛盾", "改\"都\"为\"除小明外都\""),
    ]
    sent, problem, fix = b.rng.choice(cases)
    problems = ["缺少主语", "语义重复", "搭配不当", "两面对一面", "否定不当", "主客颠倒", "前后矛盾"]
    b.choice("句子\"%s\"的语病类型是？" % sent, problem,
             [p for p in problems if p != problem][:3],
             "语病是%s，应%s。" % (problem, fix), ["病句辨析"], difficulty=3)


# 判断题函数只放一份，选择题/填空题函数多放几份以加权，避免判断题占比过高
PRIMARY_FNS = [c_poem_next, c_poem_next, c_poem_fill, c_idiom_mean, c_idiom_mean,
               c_idiom_judge, c_lit_judge, c_rhetoric, c_rhetoric,
               c_assoc, c_assoc, c_poem_judge]
JUNIOR_FNS = PRIMARY_FNS + [c_poem_prev, c_poem_prev, c_poem_author, c_poem_author,
                            c_idiom_fill, c_lit, c_lit, c_pronunciation,
                            c_bug_sentence, c_bug_sentence]
SENIOR_FNS = JUNIOR_FNS + [c_poem_author, c_lit, c_bug_sentence]


def generate(builder):
    g = builder.grade
    fns = PRIMARY_FNS if g <= 6 else (JUNIOR_FNS if g <= 9 else SENIOR_FNS)
    target = 1000
    stall = 0
    while len(builder.items) < target:
        before = len(builder.items)
        builder.rng.choice(fns)(builder)
        if len(builder.items) == before:
            stall += 1
            if stall > 80:
                idiom = builder.rng.choice(IDIOMS)
                builder.judge("成语\"%s\"的意思是%s。" % (idiom[0], idiom[1]), True,
                              "%s：%s。" % idiom, ["成语理解"])
        else:
            stall = 0
