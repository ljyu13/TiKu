def _answers(facts):
    return [x[1] for x in facts]


def fact_forward(b, facts, prefix):
    """正向单选：问 q 答 a。"""
    q, ans, kp = b.rng.choice(facts)
    others = b.rng.sample([x for x in _answers(facts) if x != ans], 3)
    b.choice("%s？" % q, ans, others, "%s%s。" % (q, ans), [prefix + kp])


def fact_reverse(b, facts, prefix):
    """整改：原反向选择题把答案词摆在题干，改为填空题留空。"""
    q, ans, kp = b.rng.choice(facts)
    lead = b.rng.choice(["", "请填空：", "根据描述填空："])
    tail = b.rng.choice(["。", "（填写正确答案）。"])
    b.fill("%s%s___%s" % (lead, q, tail), ans,
           "%s%s。" % (q, ans), [prefix + kp], difficulty=3)


def fact_fill(b, facts, prefix):
    q, ans, kp = b.rng.choice(facts)
    b.fill("%s___。" % q, ans, "%s%s。" % (q, ans), [prefix + kp])


def fact_judge_true(b, facts, prefix):
    q, ans, kp = b.rng.choice(facts)
    b.judge("%s%s。" % (q, ans), True, "%s%s，表述正确。" % (q, ans), [prefix + kp])


def fact_judge_false(b, facts, prefix):
    """整改：原错误判断题把乱词塞进题干，改为把正确词位置留空的填空题。"""
    q, ans, kp = b.rng.choice(facts)
    lead = b.rng.choice(["", "补充完整：", "完成填空："])
    tail = b.rng.choice(["。", "（填写正确答案）。"])
    b.fill("%s%s___%s" % (lead, q, tail), ans,
           "%s%s。" % (q, ans), [prefix + kp])


def builtin_judge(b, judges, prefix):
    sent, ok, ana = b.rng.choice(judges)
    b.judge(sent, ok, ana, [prefix])


