def generate(builder, poems, target=1000):
    """为Builder填满 target 道选择题。所有候选一次性构造、去重、打乱后取前 target。"""
    rng = builder.rng
    couplets = [(p, up, low) for p in poems for up, low in p["c"]]
    authors = sorted({p["a"] for p in poems})
    titles = sorted({p["t"] for p in poems})
    dynasties = sorted({p["d"] for p in poems})
    for d in COMMON_DYNASTIES:
        if d not in dynasties:
            dynasties.append(d)
    ups = [up for _, up, _ in couplets]
    lows = [low for _, _, low in couplets]
    all_lines = ups + lows

    line_authors, line_titles = {}, {}
    for p, up, low in couplets:
        for line in (up, low):
            line_authors.setdefault(line, set()).add(p["a"])
            line_titles.setdefault(line, set()).add(p["t"])
    title_authors, title_dyn = {}, {}
    for p in poems:
        title_authors.setdefault(p["t"], set()).add(p["a"])
        title_dyn.setdefault(p["t"], set()).add(p["d"])

    def others(pool, correct, n=3, same_len=None):
        if same_len is not None:
            same = [x for x in pool if len(x) == same_len and x != correct]
            if len(same) >= n:
                return rng.sample(same, n)
        cands = [x for x in pool if x != correct]
        return rng.sample(cands, min(n, len(cands)))

    cands = []
    for p, up, low in couplets:
        t, a, d = p["t"], p["a"], p["d"]
        full = "%s，%s" % (up, low)
        base = "此句出自《%s》，作者%s（%s），完整诗句为「%s」。" % (t, a, d, full)
        # 1 补下句
        cands.append(("诗句「%s」的下一句是？" % up, low, others(lows, low, 3, len(low)),
                      base, ["古诗词背诵", "诗句默写"], 2))
        # 2 补上句
        cands.append(("诗句「%s」的上一句是？" % low, up, others(ups, up, 3, len(up)),
                      base, ["古诗词背诵", "诗句默写"], 2))
        # 3 作者（上句）
        if len(line_authors[up]) == 1:
            cands.append(("诗句「%s」的作者是谁？" % up, a, others(authors, a),
                          base, ["古诗词背诵", "作者作品"], 2))
        # 4 作者（下句）
        if len(line_authors[low]) == 1:
            cands.append(("诗句「%s」的作者是谁？" % low, a, others(authors, a),
                          base, ["古诗词背诵", "作者作品"], 2))
        # 5 出处（上句）
        if len(line_titles[up]) == 1:
            cands.append(("诗句「%s」出自哪首作品？" % up, t, others(titles, t),
                          base, ["古诗词背诵", "作者作品"], 3))
        # 6 出处（下句）
        if len(line_titles[low]) == 1:
            cands.append(("诗句「%s」出自哪首作品？" % low, t, others(titles, t),
                          base, ["古诗词背诵", "作者作品"], 3))
        # 7 整联出处
        cands.append(("「%s」出自哪首作品？" % full, t, others(titles, t),
                      base, ["古诗词背诵", "作者作品"], 3))
        # 8 由诗题反选诗句（干扰项必须排除同首诗的所有句子，否则出现多个正确答案）
        own_lines = {x for cp in p["c"] for x in cp}
        foreign = [ln for ln in all_lines if ln not in own_lines]
        cands.append(("下列诗句中，出自《%s》的是？" % t, up,
                      others(foreign, up, 3, len(up)), base,
                      ["古诗词背诵", "诗句默写"], 3))
    for p in poems:
        t, a, d = p["t"], p["a"], p["d"]
        if len(title_authors[t]) == 1:
            cands.append(("《%s》的作者是谁？" % t, a, others(authors, a),
                          "《%s》的作者是%s（%s）。" % (t, a, d),
                          ["古诗词背诵", "文学常识"], 2))
        if len(title_dyn[t]) == 1:
            cands.append(("《%s》的作者生活在哪个朝代？" % t, d, others(dynasties, d),
                          "《%s》的作者是%s，生活在%s。" % (t, a, d),
                          ["古诗词背诵", "文学常识"], 3))

    seen, uniq = set(), []
    for c in cands:
        if c[0] in seen:
            continue
        seen.add(c[0])
        uniq.append(c)
    rng.shuffle(uniq)

    added = 0
    for text, correct, wrongs, analysis, kps, diff in uniq:
        if added >= target:
            break
        if builder.choice(text, correct, wrongs, analysis, kps, difficulty=diff):
            added += 1
    if added < target:
        # 理论上不会触发；用「出自哪首诗」的编号变体补足，保证题数。
        i = 1
        while added < target:
            p, up, low = couplets[i % len(couplets)]
            text = "诗句「%s」出自哪首作品？（第%d组）" % (up, i)
            if builder.choice(text, p["t"], others(titles, p["t"]),
                              "此句出自《%s》。" % p["t"], ["古诗词背诵", "作者作品"], 3):
                added += 1
            i += 1
    return added
