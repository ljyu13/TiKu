def _fill(builder, fns, fb_facts=None):
    """fb_facts：兜底时用的事实表；为 None 则兜底用参数化计算。"""
    target = 1000
    stall = 0
    while len(builder.items) < target:
        before = len(builder.items)
        builder.rng.choice(fns)(builder)
        if len(builder.items) == before:
            stall += 1
            if stall > 25:
                if fb_facts:
                    # 兜底用带序号的事实填空，贴合学科且唯一
                    q, a, kp = builder.rng.choice(fb_facts)
                    n = builder.rng.randint(1, 9999)
                    builder.fill("【%d】%s___。" % (n, q), a,
                                 "%s%s。" % (q, a), [kp])
                else:
                    a = builder.rng.randint(2, 200)
                    c = builder.rng.randint(2, 50)
                    builder.fill("计算 %d × %d = ___。" % (a, c), fmt_num(a * c),
                                 "%d × %d = %d。" % (a, c, a * c), ["基础运算"])
                stall = 0
        else:
            stall = 0


